/// A key file, owner-readable only where that is expressible. Local to this file rather than
/// shared with `tests_signing`, which is a sibling module and cannot lend its helpers.
fn key_file(dir: &std::path::Path, name: &str, bytes: &[u8]) -> std::path::PathBuf {
    let p = dir.join(name);
    std::fs::write(&p, bytes).unwrap();
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        std::fs::set_permissions(&p, std::fs::Permissions::from_mode(0o600)).unwrap();
    }
    p
}

/// Load in the way that reaches the *length* rule on every platform: off Unix, `Key::load` refuses
/// at the ACL check first, and a test of the length rule there would be asserting the wrong thing.
fn load_reaching_the_length_rule(path: &std::path::Path) -> Result<Key, FerroError> {
    let check = if PROTECTION_IS_CHECKABLE {
        PermissionCheck::Enforce
    } else {
        PermissionCheck::AcceptUnverifiable
    };
    Key::load_with(path, check)
}

/// **A 32-byte file of NULs loads, and it is the same key as the empty file the same guard
/// refuses.** `Key::load` measures the key's *length* and nothing else, and RFC 2104 zero-pads a
/// short key to the block — so 32 zero bytes and 0 bytes prepare the identical pads and mint
/// identical tags. A file made by `truncate -s 32 key`, by a sparse copy, or by a generator that
/// wrote nothing and exited 0 passes every check this module makes.
///
/// This is not a forgery: an attacker still has to know that the key is zeros. It is a guard that
/// refuses one spelling of a key and accepts another that is cryptographically the same one.
#[test]
fn a_key_file_of_thirty_two_nul_bytes_loads_and_is_the_empty_key() {
    let zero = Key::from_bytes_for_test(vec![0u8; MIN_KEY_BYTES]).expect("32 bytes clears the rule");
    let body = msg_of(64);
    // Identical to the key `Key::load` refuses outright, because both prepare an all-zero block.
    assert_eq!(zero.tag(&body).to_vec(), hmac_sha256(&[], &[&DOMAIN[..], &body[..]].concat()).to_vec());
    assert_eq!(zero.tag(&body).to_vec(), hmac_sha256(&[0u8; 64], &[&DOMAIN[..], &body[..]].concat()).to_vec());

    // And it is a key a file on disk can hold: the length rule is the only content rule there is.
    let dir = tempfile::tempdir().unwrap();
    let empty = key_file(dir.path(), "empty.key", &[]);
    let nuls = key_file(dir.path(), "nuls.key", &[0u8; MIN_KEY_BYTES]);
    let refused = load_reaching_the_length_rule(&empty).unwrap_err();
    assert!(format!("{refused}").contains("is 0 byte(s)"), "unexpected refusal: {refused}");
    let loaded = load_reaching_the_length_rule(&nuls).expect("32 NUL bytes is a key this build accepts");
    assert_eq!(loaded.len(), MIN_KEY_BYTES);
    assert_eq!(loaded.tag(&body), zero.tag(&body));
    // A frame signed by the zero key verifies under it, so a cluster would run on it happily.
    let signed = sign_frame(&loaded, &body).unwrap();
    assert_eq!(verify_frame(&zero, &signed).unwrap(), &body[..]);
}
