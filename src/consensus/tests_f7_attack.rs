// ---------------------------------------------------------------------------------------------
// Is `DOMAIN || message` unambiguous, and is the private multi-part form?
// ---------------------------------------------------------------------------------------------

/// A fixed-length prefix cannot be moved, so no two distinct bodies share an authenticated region.
///
/// Stated as the thing an attacker would need: a body `b` whose `DOMAIN || b` equals
/// `DOMAIN || b'` for some `b' != b`. Swept over bodies that start with, end with, or wholly
/// contain the domain bytes — the shapes that would collide if the prefix were variable-length or
/// if it were a separator rather than a prefix.
#[test]
fn no_two_distinct_bodies_share_an_authenticated_region() {
    let mut bodies: Vec<Vec<u8>> = Vec::new();
    bodies.push(Vec::new());
    bodies.push(DOMAIN.to_vec());
    bodies.push([&DOMAIN[..], &DOMAIN[..]].concat());
    bodies.push([&DOMAIN[..], b"tail"].concat());
    bodies.push([b"head".as_slice(), &DOMAIN[..]].concat());
    for n in [1usize, 25, 26, 27, 63, 64, 65] {
        bodies.push(msg_of(n));
        bodies.push([&DOMAIN[..n.min(26)], &msg_of(n)[..]].concat());
    }
    let key = a_key(32);
    let mut seen: std::collections::HashMap<[u8; MAC_LEN], Vec<u8>> = std::collections::HashMap::new();
    for b in &bodies {
        let region = [&DOMAIN[..], &b[..]].concat();
        // The authenticated region determines the body: strip the fixed prefix and it is back.
        assert_eq!(&region[..26], &DOMAIN[..]);
        assert_eq!(&region[26..], &b[..]);
        if let Some(prev) = seen.insert(key.tag(b), b.clone()) {
            assert_eq!(&prev, b, "two distinct bodies produced one tag");
        }
    }
    assert_eq!(seen.len(), bodies.len(), "a body was signed twice or two bodies collided");
}

/// **The private multi-part form IS ambiguous, and the only thing containing it is that no caller
/// can reach it with two variable-length pieces.** Demonstrated rather than argued, because the
/// doc comment on `hmac_sha256_parts` asserts exactly this and a reader should be able to see the
/// hazard it is claiming to have avoided.
#[test]
fn the_multi_part_form_is_ambiguous_and_only_its_callers_make_it_safe() {
    let k = key_of(32);
    // Same bytes, different split: one tag. This is the ambiguity.
    assert_eq!(
        hmac_sha256_parts(&k, &[b"ab", b"c"]),
        hmac_sha256_parts(&k, &[b"a", b"bc"]),
        "the pieces are concatenated in the hash, so the split point is not authenticated"
    );
    // And the fixed-length first piece is what removes it: with `DOMAIN` at the front, the second
    // piece begins at 26 and an attacker cannot move that boundary.
    for n in [0usize, 1, 26, 38, 102] {
        assert_eq!(
            hmac_sha256_parts(&k, &[&DOMAIN, &msg_of(n)]),
            hmac_sha256(&k, &[&DOMAIN[..], &msg_of(n)[..]].concat()),
            "streaming the {n}-byte body after the domain is not hashing their join"
        );
    }
}

