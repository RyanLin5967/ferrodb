// The key's equivalence classes. RFC 2104 behaviour, restated as what it costs a cluster.
// ---------------------------------------------------------------------------------------------

/// **Two different key files can be the same key.** A key under the block is zero-padded to it, so
/// a 32-byte file and the same 32 bytes followed by any number of zeros — up to the 64-byte block —
/// mint identical tags and each verifies the other's frames.
///
/// This is RFC 2104 and every conforming HMAC does it; it is pinned here because `Key::load` reads
/// a whole file and a trailing newline is exactly how a 32-byte key becomes a 33-byte one.
#[test]
fn a_key_and_the_same_key_zero_padded_are_one_key() {
    let base = key_of(32);
    let frame_body = msg_of(64);
    for pad in 1..=32usize {
        let mut padded = base.clone();
        padded.resize(32 + pad, 0);
        let a = Key::from_bytes_for_test(base.clone()).unwrap();
        let b = Key::from_bytes_for_test(padded).unwrap();
        assert_eq!(a.len() + pad, b.len());
        assert_eq!(a.tag(&frame_body), b.tag(&frame_body), "{pad} zero bytes changed nothing");
        let signed = sign_frame(&a, &frame_body).unwrap();
        assert!(verify_frame(&b, &signed).is_ok(), "the padded key verified the base key's frame");
    }
    // A trailing *newline* is a different byte and is not in the class, which is the one comfort.
    let mut newline = base.clone();
    newline.push(b'\n');
    let n = Key::from_bytes_for_test(newline).unwrap();
    assert_ne!(Key::from_bytes_for_test(base).unwrap().tag(&frame_body), n.tag(&frame_body));
}

/// **A key over the block and its own SHA-256 are one key.** RFC 2104 replaces a long key by its
/// digest, so a 65-byte key file and a 32-byte file holding that file's digest are interchangeable:
/// either verifies the other's frames.
#[test]
fn a_long_key_and_its_digest_are_one_key() {
    let frame_body = msg_of(37);
    for long_len in [65usize, 66, 96, 128, 131, 200] {
        let long = key_of(long_len);
        let digest = sha256(&long).to_vec();
        let a = Key::from_bytes_for_test(long).unwrap();
        let b = Key::from_bytes_for_test(digest).unwrap();
        assert_eq!(a.len(), long_len);
        assert_eq!(b.len(), 32);
        assert_eq!(a.tag(&frame_body), b.tag(&frame_body), "a {long_len}-byte key is not its digest");
        let signed = sign_frame(&a, &frame_body).unwrap();
        assert!(verify_frame(&b, &signed).is_ok());
    }
    // Exactly 64 is *not* in the class: the rule is `> BLOCK`, and the boundary is where an
    // implementation puts the `>=` by mistake.
    let sixty_four = key_of(64);
    let d = sha256(&sixty_four).to_vec();
    assert_ne!(
        Key::from_bytes_for_test(sixty_four).unwrap().tag(&frame_body),
        Key::from_bytes_for_test(d).unwrap().tag(&frame_body),
        "a key of exactly one block must not be replaced by its digest"
    );
}

