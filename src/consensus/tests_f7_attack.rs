/// 330 (key length, message length) pairs, every one checked against CPython.
///
/// The key lengths straddle the block on both sides — 63, 64, 65, 66 — because RFC 2104's
/// "hash a key longer than the block" rule is the one an implementation gets off by one. The
/// message lengths straddle 55/56 (where SHA-256's length field forces an extra block) and
/// 63/64/65, 127/128/129, 191/192.
#[test]
fn hmac_agrees_with_cpython_at_every_key_and_message_boundary() {
    assert_eq!(HMAC_VECTORS.len(), 330, "the table was regenerated with different inputs");
    for &(key_len, msg_len, expected) in HMAC_VECTORS {
        let got = to_hex(&hmac_sha256(&key_of(key_len), &msg_of(msg_len)));
        assert_eq!(
            got, expected,
            "hmac_sha256 disagrees with CPython for a {key_len}-byte key over a {msg_len}-byte \
             message"
        );
    }
}

/// The empty key, called out on its own because a length of zero is the input a `copy_from_slice`
