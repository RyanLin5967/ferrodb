// ---------------------------------------------------------------------------------------------
// The same question again, with pseudo-random inputs. Every table above is an affine byte
// sequence, and an implementation bug that depends on key *content* — a mis-XORed pad, a carry —
// could hide inside one. These rows have random keys and random messages, and CPython still owns
// every expected value.
// ---------------------------------------------------------------------------------------------

/// xorshift64*, reproduced byte for byte by the Python generator that emitted the tables.
struct Xorshift(u64);

impl Xorshift {
    fn next(&mut self) -> u64 {
        let mut x = self.0;
        x ^= x >> 12;
        x ^= x << 25;
        x ^= x >> 27;
        self.0 = x;
        x.wrapping_mul(0x2545_f491_4f6c_dd1d)
    }

    fn bytes(&mut self, n: usize) -> Vec<u8> {
        (0..n).map(|_| (self.next() & 0xff) as u8).collect()
    }
}

/// The row's inputs, rebuilt from its seed exactly as the generator built them.
fn random_row(seed: u64) -> (usize, usize, Vec<u8>, Vec<u8>) {
    let mut r = Xorshift(seed);
    let key_len = 1 + (r.next() % 200) as usize;
    let msg_len = (r.next() % 300) as usize;
    let key = r.bytes(key_len);
    let msg = r.bytes(msg_len);
    (key_len, msg_len, key, msg)
}

#[test]
fn hmac_agrees_with_cpython_on_two_hundred_random_key_and_message_pairs() {
    assert_eq!(RANDOM_VECTORS.len(), 200);
    let mut key_lens = std::collections::BTreeSet::new();
    for &(seed, key_len, msg_len, expected) in RANDOM_VECTORS {
        let (kl, ml, key, msg) = random_row(seed);
        assert_eq!((kl, ml), (key_len, msg_len), "the Rust and Python generators diverged");
        assert_eq!(to_hex(&hmac_sha256(&key, &msg)), expected, "seed {seed}");
        key_lens.insert(key_len);
    }
    // The sweep is only worth anything if it straddles the block; say so rather than assume it.
    assert!(key_lens.iter().any(|&k| k < 64), "no key under the block");
    assert!(key_lens.iter().any(|&k| k > 64), "no key over the block");
}

#[test]
fn tag_agrees_with_cpython_on_random_keys_and_bodies() {
    assert_eq!(RANDOM_TAG_VECTORS.len(), 168);
    for &(seed, key_len, body_len, expected) in RANDOM_TAG_VECTORS {
        let (kl, bl, key, body) = random_row(seed);
        assert_eq!((kl, bl), (key_len, body_len));
        let k = Key::from_bytes_for_test(key).expect("the table keeps only rows at or over 32");
        assert_eq!(to_hex(&k.tag(&body)), expected, "seed {seed}");
        // And the frame layer agrees with the primitive it is built on.
        let signed = sign_frame(&k, &body).unwrap();
        assert_eq!(to_hex(&signed[..MAC_LEN]), expected);
        assert_eq!(verify_frame(&k, &signed).unwrap(), &body[..]);
    }
}

