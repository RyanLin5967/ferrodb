/// Every rearrangement of two genuine frames that an attacker can compute without the key.
///
/// The attacker is given two frames minted by the real key and may cut, swap, xor, reverse and
/// re-join them at any offset. Nothing they can build authenticates unless it is one of the two
/// frames they were given, unchanged.
#[test]
fn no_splice_of_two_genuine_frames_authenticates() {
    let key = a_key(32);
    let b1 = msg_of(40);
    let b2: Vec<u8> = msg_of(40).iter().map(|b| b ^ 0xa5).collect();
    let f1 = sign_frame(&key, &b1).unwrap();
    let f2 = sign_frame(&key, &b2).unwrap();
    let (t1, body1) = f1.split_at(MAC_LEN);
    let (t2, body2) = f2.split_at(MAC_LEN);

    let mut candidates: Vec<Vec<u8>> = Vec::new();
    candidates.push([t1, body2].concat());
    candidates.push([t2, body1].concat());
    candidates.push([t1, &t2[..]].concat());
    candidates.push([&t1.iter().zip(t2).map(|(a, b)| a ^ b).collect::<Vec<u8>>()[..], body1].concat());
    candidates.push([&t1.iter().rev().copied().collect::<Vec<u8>>()[..], body1].concat());
    candidates.push([&body1[..MAC_LEN], body1].concat());
    for k in 0..body1.len() {
        candidates.push([t1, &body1[..k], &body2[k..]].concat());
        candidates.push([t2, &body2[..k], &body1[k..]].concat());
    }
    // Slide the split: take the whole 72-byte frame and re-cut it everywhere. `verify_frame` cuts
    // at 32 by construction, so this is the attacker shifting the *content* instead.
    for shift in 1..f1.len() {
        candidates.push(f1[shift..].iter().chain(f1[..shift].iter()).copied().collect());
    }

    let mut tried = 0usize;
    for c in &candidates {
        assert_ne!(c, &f1);
        assert_ne!(c, &f2);
        assert!(
            verify_frame(&key, c).is_err(),
            "a {}-byte splice of two genuine frames authenticated",
            c.len()
        );
        tried += 1;
    }
    assert!(tried >= 100, "only {tried} splices were tried");
    // The two originals still pass, so the sweep above is not vacuously refusing everything.
    assert_eq!(verify_frame(&key, &f1).unwrap(), &b1[..]);
    assert_eq!(verify_frame(&key, &f2).unwrap(), &b2[..]);
}

/// `verify_frame` splits at a fixed offset, so a body that is *itself* a valid signed frame would
/// let an attacker strip the outer tag and deliver the inner message. The first half of this test
/// builds that frame and shows the strip working; the second half shows why no genuine sender can
/// produce one — a real encoded body would have to open with a valid tag over its own remainder,
/// which needs the key.
#[test]
fn a_nested_frame_can_be_stripped_but_no_genuine_body_is_one() {
    let key = a_key(32);
    let inner_body = msg_of(24);
    let inner = sign_frame(&key, &inner_body).unwrap();
    let outer = sign_frame(&key, &inner).unwrap();
    assert_eq!(verify_frame(&key, &outer).unwrap(), &inner[..]);
    // Rewriting the (unauthenticated) length header to drop the outer tag yields a frame that
    // verifies for `inner_body`. This is the shape; the next assertion is why it is not reachable.
    assert_eq!(verify_frame(&key, &outer[MAC_LEN..]).unwrap(), &inner_body[..]);

    for term in [0u64, 1, u64::MAX] {
        for body in [
            Body::PreVote { last_term: term, last_round: 9 },
            Body::RequestVoteResp { granted: true },
            Body::AppendResp { success: false, matched: 3, hint: 4, digest: 5 },
        ] {
            let m = Message { from: NodeId(7), to: NodeId(9), term, body };
            let frame = encode_signed(&m, None).unwrap();
            let encoded_body = &frame[5..];
            assert!(
                verify_frame(&key, encoded_body).is_err(),
                "a genuine encoded message body was itself a valid signed frame"
            );
        }
    }
}

