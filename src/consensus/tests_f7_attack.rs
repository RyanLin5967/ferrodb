/// A mac of any length but 32 is refused, including a correct tag with a byte added or removed and
/// a correct tag repeated. Nothing indexes past the end and nothing panics.
#[test]
fn verify_refuses_every_mac_length_but_thirty_two() {
    let key = a_key(32);
    let message = msg_of(70);
    let real = key.tag(&message);
    for len in 0..=64usize {
        let mut candidate = Vec::new();
        while candidate.len() < len {
            let take = (len - candidate.len()).min(MAC_LEN);
            candidate.extend_from_slice(&real[..take]);
        }
        assert_eq!(
            key.verify(&message, &candidate),
            len == MAC_LEN,
            "a {len}-byte mac built from the real tag's bytes was judged wrongly"
        );
    }
    // The truncated-prefix case said explicitly: 31 correct bytes is not 31/32 of a pass.
    assert!(!key.verify(&message, &real[..31]));
    assert!(!key.verify(&message, &[&real[..], &[0u8]].concat()));
    assert!(!key.verify(&message, &[]));
}

/// Inner bodies of 0, 31, 32 and 33 bytes, and frames too short to hold a tag.
///
/// The 32-byte frame is the interesting one: it authenticates an **empty** body, which
/// `verify_frame` must accept (the tag is over nothing and is valid) and `decode` must then refuse
/// as a message with no fields — an error, never a panic and never a `Message`.
#[test]
fn verify_frame_at_the_tag_length_boundary() {
    let key = a_key(32);
    for len in 0..MAC_LEN {
        let err = verify_frame(&key, &msg_of(len)).unwrap_err();
        assert!(
            format!("{err}").contains("cannot hold its 32-byte authentication tag"),
            "a {len}-byte frame gave the wrong refusal: {err}"
        );
    }
    for body_len in [0usize, 1, 31, 32, 33, 63, 64, 65] {
        let body = msg_of(body_len);
        let signed = sign_frame(&key, &body).unwrap();
        assert_eq!(signed.len(), body_len + MAC_LEN);
        assert_eq!(verify_frame(&key, &signed).unwrap(), &body[..]);
        // ...and the same bytes under a different key are refused.
        assert!(verify_frame(&a_key(33), &signed).is_err());
    }
    // The empty body authenticates, and then the parser refuses it.
    let empty = sign_frame(&key, &[]).unwrap();
    assert_eq!(empty.len(), MAC_LEN);
    assert!(verify_frame(&key, &empty).unwrap().is_empty());
    assert!(decode_verified(&empty, Some(&key)).is_err(), "an empty body must not decode");
}

/// Every single-bit flip of a signed frame — tag bytes and body bytes alike — is refused.
