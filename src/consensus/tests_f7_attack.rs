/// Every two-part and three-part split of a message, through the incremental `update`.
///
/// This is the state machine `Key::tag` relies on when it streams the domain prefix instead of
/// joining it: if `update` mishandled a partial block that exactly fills, or a call that arrives
/// with a block already part-full, the split at 26 bytes would be the one to find it. 26 offsets
/// times every pair of cut points is 6,000-odd hashes and runs in well under a second.
#[test]
fn every_split_of_a_message_hashes_to_the_same_digest() {
    for len in [0usize, 1, 55, 56, 63, 64, 65, 90, 127, 128, 129, 191, 192, 200] {
        let m = msg_of(len);
        let whole = sha256(&m);
        for i in 0..=len {
            let mut s = Sha256::new();
            s.update(&m[..i]);
            s.update(&m[i..]);
            assert_eq!(s.finish(), whole, "a two-part split at {i} of {len} bytes diverged");
            for j in i..=len {
                let mut s = Sha256::new();
                s.update(&m[..i]);
                s.update(&m[i..j]);
                s.update(&m[j..]);
                assert_eq!(
                    s.finish(),
                    whole,
                    "a three-part split at {i}/{j} of {len} bytes diverged"
                );
            }
        }
    }
}

/// An `update` with nothing in it must not disturb the block that is part-full.
#[test]
fn empty_updates_anywhere_change_nothing() {
    let m = msg_of(100);
    let whole = sha256(&m);
    for i in 0..=100 {
        let mut s = Sha256::new();
        s.update(&[]);
        s.update(&m[..i]);
        s.update(&[]);
        s.update(&[]);
        s.update(&m[i..]);
        s.update(&[]);
        assert_eq!(s.finish(), whole, "an empty update beside offset {i} changed the digest");
    }
}

