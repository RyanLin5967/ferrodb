//! Throwaway adversarial probes against F7's MAC. **Not a contract** — these exist to try to break
//! [`super::verify_frame`] and [`super::hmac_sha256`], not to describe what they promise.
//!
//! Four things are deliberately different from `tests_signing.rs`:
//!
//! * **Every expected value comes from CPython's `hmac`/`hashlib`, not from this crate.** The
//!   tables below were emitted by `scripts/gen_f7_attack_vectors.py` (kept beside this file);
//!   a test whose expectation is produced by calling the subject proves only that the subject is
//!   deterministic.
//! * **The forgery machinery is proved to work before it is aimed at HMAC.** A detector that finds
//!   nothing is not a clean result until it has been made to fire, so
//!   `length_extension_forges_a_sha256_key_prefix_mac` mounts a real length-extension attack
//!   against `sha256(key || message)` and shows it succeeding, using a second SHA-256 written in
//!   this file. Only then is the same attack aimed at `hmac_sha256`.
//! * **The tables are two generators, not one.** `scripts/gen_f7_attack_vectors.py` walks the
//!   boundaries with affine byte patterns; `scripts/gen_f7_attack_random_vectors.py` walks random
//!   keys and messages, because an affine input can hide a bug that depends on key content.
//! * **The boundaries are swept, not sampled.** Bodies are chosen at every offset where the
//!   26-byte [`DOMAIN`] prefix can straddle a SHA-256 block or its length padding.
//!
//! # What these tests were shown to catch
//!
//! Run once green, a suite proves nothing. Each line below is a change made to the **subject** —
//! `signing.rs` or `provenance/sha256.rs` — followed by the tests here that failed because of it.
//! The tree was restored and re-verified byte for byte after every one.
//!
//! | change to the subject | tests killed |
//! |---|---|
//! | RFC 2104's long-key rule `> BLOCK` becomes `>= BLOCK` | 8 |
//! | `Sha256::update`'s partial-block fill off by one (`64 - used` -> `63 - used`) | 8 |
//! | `verify_frame`'s short-frame guard removed | 2 |
//! | `Key::tag` drops the [`DOMAIN`] prefix | 3 |
//! | `Sha256::finish` writes the length at the wrong offset (`!= 56` -> `< 56`) | 10 |
//! | `Key::verify` silently compares only the first 16 tag bytes | 2 |
//! | `constant_time_eq` short-circuits on the first differing byte | **0 — see below** |
//!
//! The last row is this file's blind spot, stated rather than left to be found: nothing here times
//! anything, so a comparison that leaks the position of the first wrong byte reads as correct to
//! every test in this module. It is not a gap in the repo — the same change fails
//! `tests_signing::constant_time_eq_does_not_short_circuit`, which is where that property lives.

