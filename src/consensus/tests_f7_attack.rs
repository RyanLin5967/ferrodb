/// Every one of the 256 keys one bit away from the real one refuses the real key's frame.
#[test]
fn no_key_one_bit_from_the_real_one_verifies_its_frames() {
    let real = key_of(32);
    let body = msg_of(50);
    let signed = sign_frame(&Key::from_bytes_for_test(real.clone()).unwrap(), &body).unwrap();
    let mut tried = 0usize;
    for i in 0..real.len() {
        for bit in 0..8 {
            let mut near = real.clone();
            near[i] ^= 1 << bit;
            let k = Key::from_bytes_for_test(near).unwrap();
            assert!(
                verify_frame(&k, &signed).is_err(),
                "the key with bit {bit} of byte {i} flipped verified another key's frame"
            );
            tried += 1;
        }
    }
    assert_eq!(tried, 256);
}

/// Eight keys, none in another's RFC 2104 equivalence class: a frame verifies under exactly the
/// key that signed it and under no other.
#[test]
fn a_frame_verifies_under_exactly_the_key_that_signed_it() {
    let lens = [32usize, 33, 40, 63, 64, 65, 96, 131];
    let keys: Vec<Key> = lens.iter().map(|&n| a_key(n)).collect();
    let body = msg_of(38);
    let frames: Vec<Vec<u8>> = keys.iter().map(|k| sign_frame(k, &body).unwrap()).collect();
    for (i, frame) in frames.iter().enumerate() {
        for (j, k) in keys.iter().enumerate() {
            assert_eq!(
                verify_frame(k, frame).is_ok(),
                i == j,
                "the frame signed by the {}-byte key was judged wrongly by the {}-byte key",
                lens[i],
                lens[j]
            );
        }
    }
    // No two of these eight are the same key, which is what makes the matrix above meaningful.
    let tags: std::collections::BTreeSet<[u8; MAC_LEN]> =
        keys.iter().map(|k| k.tag(&body)).collect();
    assert_eq!(tags.len(), keys.len());
}

